const assert = require('assert');
const fs = require('fs');
const path = require('path');
const output = path.resolve(process.argv[2] || 'public');
const read = url => fs.readFileSync(path.join(output, url.replace(/^\//, ''), 'index.html'), 'utf8');
const attrs = tag => Object.fromEntries([...tag.matchAll(/([^\s=<>]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/g)].map(m=>[m[1],m[2]??m[3]??m[4]]));
const links = html => [...html.matchAll(/<a\b[^>]*>/g)].map(m=>attrs(m[0]));
const graph = html => [...html.matchAll(/(<script\b[^>]*>)([\s\S]*?)<\/script>/g)].filter(m=>attrs(m[1]).type==='application/ld+json').flatMap(m=>JSON.parse(m[2])['@graph']||[]);
const plain = html => html.replace(/<[^>]+>/g,' ').replace(/\s+/g,' ').trim();
const profiles = require('../data/condition_local_profiles.json');
const conditions = {"tic":"틱장애","adhd":"ADHD","panic":"공황장애","anxiety":"불안장애·공포증","insomnia":"수면·불면증","autonomic":"자율신경실조증","hyperhidrosis":"다한증","ibs":"과민성대장증후군","syncope":"미주신경성 실신"};
const regions = ["용인","경기광주","성남","이천","안성","여주","판교","수지"];
const sitemap = fs.readFileSync(path.join(output,'sitemap.xml'),'utf8');
for(const [slug,name] of Object.entries(conditions)){
 const parentUrl='/conditions/'+slug+'/';
 const parent=read(parentUrl);
 const sourceFaq=graph(parent).find(n=>n['@type']==='FAQPage').mainEntity;
 const sourceColumns=links(parent).filter(a=>a.class==='reference-column').map(a=>a.href);
 const nav=parent.match(/<nav\b[^>]*class=(?:"condition-region-links"|condition-region-links)[^>]*>([\s\S]*?)<\/nav>/)?.[1];
 assert(nav,slug+': navigation');
 assert.strictEqual(plain(nav),'1 2 3 4 5 6 7 8',slug+': numbers only');
 assert.deepStrictEqual(links(nav).map(a=>a.href),regions.map((_,i)=>parentUrl+(i+1)+'/'));
 assert.strictEqual(profiles[slug].symptom_types.length,4);
 assert.strictEqual(profiles[slug].steps.length,4);
 const descriptions=new Set();
 for(const [i,region] of regions.entries()){
  const url=parentUrl+(i+1)+'/';
  const html=read(url), text=plain(html), expected=region+' '+name+' 치료 병원 ㅣ 해아림한의원';
  assert.strictEqual(html.match(/<title>([^<]+)<\/title>/)[1],expected);
  assert.strictEqual(html.match(/<h1\b[^>]*>([^<]+)<\/h1>/)[1],expected);
  assert.strictEqual((html.match(/<h1\b/g)||[]).length,1);
  const meta=[...html.matchAll(/<meta\b[^>]*>/g)].map(m=>attrs(m[0]));
  assert.strictEqual(meta.find(m=>m.property==='og:title').content,expected);
  assert(!meta.some(m=>m.name==='robots'&&/noindex/i.test(m.content)));
  const desc=meta.find(m=>m.name==='description').content;
  assert(!descriptions.has(desc));descriptions.add(desc);
  assert([...html.matchAll(/<link\b[^>]*>/g)].map(m=>attrs(m[0])).some(m=>m.rel==='canonical'&&m.href==='https://healimbd.com'+url));
  assert(sitemap.includes('https://healimbd.com'+url));
  assert(html.includes('daegu-local-hero')&&!html.includes('condition-photo-hero'));
  assert(text.includes(region+'에서 '+name+' 치료를 고민'));
  assert(text.includes('2. '+name+' 주요 증상과 4단계 진료 과정'));
  assert(text.includes(name+' 진료 본페이지 전체보기'));
  for(const item of profiles[slug].symptom_types)assert(text.includes(item.title)&&text.includes(item.text),url+': correct symptoms');
  assert(text.includes(profiles[slug].symptom_note));
  if(profiles[slug].alert)assert(text.includes(profiles[slug].alert),url+': safety advice');
  const nodes=graph(html);
  const faq=nodes.find(n=>n['@type']==='FAQPage').mainEntity;
  assert.strictEqual(faq.length,7);
  assert.deepStrictEqual(faq.slice(-4),sourceFaq.slice(-4),url+': condition-specific FAQs');
  for(const q of faq)assert(text.includes(q.name)&&text.includes(q.acceptedAnswer.text),url+': visible FAQ');
  assert.deepStrictEqual(links(html).filter(a=>a.class==='daegu-local-column-card').map(a=>a.href),sourceColumns);
  assert.strictEqual(links(html).filter(a=>a.class==='daegu-local-review-card'&&a.href==='/reviews/guide/').length,3);
  const crumbs=nodes.find(n=>n['@type']==='BreadcrumbList').itemListElement;
  assert.strictEqual(crumbs.find(c=>c.position===2).item,'https://healimbd.com'+parentUrl);
  assert.strictEqual(crumbs.find(c=>c.position===2).name,name+' 진료 안내');
  assert(links(html).some(a=>a.class?.includes('daegu-local-naver')&&a.href));
  if(slug!=='tic')assert(!text.includes('운동틱과 음성틱이 함께 보이거나 욕설을 하지 않는다는 사실만으로'),url+': no tic fallback');
  for(const root of ['/','/guide/'])assert(!links(read(root)).some(a=>a.href===url),url+': not a primary treatment-list card');
 }
}
assert(!fs.existsSync(path.join(output,'condition-local/index.html')));
console.log('Verified all 72 regional pages, nine numeric navigations, clinical content and metadata.');
